package router

import (
	"log/slog"
	"time"

	"github.com/gofiber/fiber/v2"
	"github.com/gofiber/fiber/v2/middleware/cors"
	"github.com/gofiber/fiber/v2/middleware/limiter"
	"lume_api/internal/config"
	"lume_api/internal/handlers"
	"lume_api/internal/middleware"
)

func Build(cfg config.Config, h *handlers.Handler, logger *slog.Logger) *fiber.App {
	app := fiber.New(fiber.Config{ErrorHandler: middleware.ErrorHandler})
	app.Use(middleware.RequestID())
	app.Use(middleware.SlogRequest(logger))
	app.Use(cors.New(cors.Config{AllowOrigins: cfg.AllowedOrigin, AllowHeaders: "Origin,Content-Type,Accept,Authorization,X-Request-Id", AllowCredentials: true}))

	app.Get("/healthz", h.Healthz)
	v1 := app.Group("/api/v1")
	auth := v1.Group("/auth")
	auth.Use(limiter.New(limiter.Config{Max: 20, Expiration: time.Minute}))
	auth.Post("/register", h.Register)
	auth.Post("/login", h.Login)
	auth.Post("/refresh", h.Refresh)
	auth.Post("/password/reset-request", h.RequestPasswordReset)
	auth.Post("/password/reset-confirm", h.ResetPassword)
	auth.Post("/email/verify-request", h.RequestEmailVerification)
	auth.Post("/email/verify", h.VerifyEmail)
	auth.Get("/me", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.Me)
	auth.Post("/logout", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.Logout)
	auth.Put("/password", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.ChangePassword)
	auth.Get("/sessions", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.ListAuthSessions)
	auth.Delete("/sessions/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.RevokeAuthSession)
	auth.Delete("/sessions", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.RevokeOtherAuthSessions)

	users := v1.Group("/users")
	authRequired := middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession)
	users.Get("/me", authRequired, h.Me)
	users.Put("/me", authRequired, h.UpdateMe)
	users.Put("/me/profile", authRequired, h.UpdateProfile)
	users.Put("/me/privacy", authRequired, h.UpdatePrivacy)
	users.Get("/me/data-export", authRequired, h.ExportMyData)
	users.Delete("/me", authRequired, h.DeleteMe)
	users.Post("/me/consent", authRequired, h.RecordConsent)
	users.Put("/me/favorites", authRequired, h.UpdateFavorites)
	users.Put("/me/annual-challenge", authRequired, h.UpdateAnnualChallenge)
	users.Get("/me/reading-sessions", authRequired, h.ListReadingSessions)
	users.Get("/me/notes", authRequired, h.ListNotes)
	users.Get("/me/goals", authRequired, h.GetReadingGoals)
	users.Put("/me/goals", authRequired, h.SaveReadingGoal)
	users.Post("/me/reading-history/import", authRequired, h.ImportReadingHistory)
	users.Get("/me/reading-history/import/:jobId", authRequired, h.GetReadingHistoryImport)
	users.Get("/:username/lists", h.PublicUserLists)
	users.Get("/:username/favorites", h.PublicFavorites)
	users.Get("/:username/annual-challenge", h.PublicAnnualChallenge)
	users.Get("/:username/logs", h.UserLogs)
	users.Get("/:username/shelf", h.UserShelf)
	users.Get("/:username/stats", h.UserStats)
	users.Get("/:username", h.PublicProfile)
	users.Post("/:id/follow", authRequired, h.Follow)
	users.Delete("/:id/follow", authRequired, h.Unfollow)
	users.Get("/:id/followers", h.Followers)
	users.Get("/:id/following", h.Following)

	books := v1.Group("/books")
	books.Get("/search", h.SearchBooks)
	books.Get("/popular", h.PopularBooks)
	books.Get("/:id", h.BookDetail)

	logs := v1.Group("/logs", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession))
	logs.Post("/", h.CreateLog)
	logs.Get("/:id", h.GetLog)
	logs.Put("/:id", h.UpdateLog)
	logs.Delete("/:id", h.DeleteLog)
	logs.Post("/:id/to-review", h.CreateReviewFromLog)
	logs.Post("/:id/like", h.LikeLog)
	logs.Delete("/:id/like", h.UnlikeLog)
	logs.Post("/:id/comments", h.AddComment)
	logs.Get("/:id/comments", h.ListComments)

	shelf := v1.Group("/shelf", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession))
	shelf.Put("/", h.UpsertShelf)
	shelf.Delete("/:bookId", h.RemoveShelfBook)

	reading := v1.Group("/reading-sessions", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession))
	reading.Post("/", h.CreateReadingSession)
	reading.Get("/:id", h.GetReadingSession)
	reading.Put("/:id", h.UpdateReadingSession)
	reading.Delete("/:id", h.DeleteReadingSession)
	reading.Get("/:id/history", h.GetReadingHistory)
	reading.Post("/:id/progress", h.RecordReadingProgress)
	reading.Get("/:id/progress", h.ListReadingProgress)
	reading.Put("/:id/status", h.SetReadingStatus)

	notes := v1.Group("/notes")
	notes.Post("/", authRequired, h.CreateNote)
	notes.Get("/:id", middleware.AuthOptional(cfg.JWTSecret, h.Auth.ValidateSession), h.GetNote)
	notes.Put("/:id", authRequired, h.UpdateNote)
	notes.Delete("/:id", authRequired, h.DeleteNote)
	notes.Post("/:id/tags", authRequired, h.CreateNoteTag)
	notes.Delete("/:id/tags/:tagId", authRequired, h.DeleteNoteTag)
	notes.Post("/:id/quotes", authRequired, h.CreateNoteQuote)
	notes.Put("/:id/quotes/:quoteId", authRequired, h.UpdateNoteQuote)
	notes.Delete("/:id/quotes/:quoteId", authRequired, h.DeleteNoteQuote)
	notes.Post("/:id/publish", authRequired, h.PublishNote)
	notes.Post("/:id/to-review", authRequired, h.CreateReviewFromNote)

	reviews := v1.Group("/reviews")
	reviews.Get("/:id", h.GetPublishedReview)
	reviews.Post("/drafts", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.CreateReviewDraft)
	reviews.Get("/drafts/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.GetReviewDraft)
	reviews.Put("/drafts/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UpdateReviewDraft)
	reviews.Delete("/drafts/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.DeleteReview)
	reviews.Post("/:id/publish", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.PublishReview)
	reviews.Post("/:id/unpublish", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UnpublishReview)
	reviews.Put("/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UpdateReview)
	reviews.Delete("/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.DeleteReview)
	reviews.Put("/:id/privacy", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UpdateReviewPrivacy)
	reviews.Get("/:id/history", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.GetReviewHistory)

	lists := v1.Group("/lists")
	lists.Get("/trending", h.TrendingLists)
	lists.Post("/", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.CreateList)
	lists.Get("/", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.MyLists)
	lists.Get("/:id", middleware.AuthOptional(cfg.JWTSecret, h.Auth.ValidateSession), h.ListDetail)
	lists.Put("/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UpdateList)
	lists.Delete("/:id", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.DeleteList)
	lists.Post("/:id/items", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.UpsertListItem)
	lists.Delete("/:id/items", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.DeleteListItem)

	feed := v1.Group("/feed")
	feed.Get("/", middleware.AuthRequired(cfg.JWTSecret, h.Auth.ValidateSession), h.FeedFollowing)
	feed.Get("/global", h.FeedGlobal)
	feed.Get("/reviews", h.FeedReviews)

	return app
}
